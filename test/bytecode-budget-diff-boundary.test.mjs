// ---- diff fake node: logs "<cwd basename> <argv>", serves ./<fn>.<k>.txt or ./<fn>.txt from its cwd (the
// driver dir), exits 1 when the DRIVER file is gone (as node does), sources ./hook.sh (adversarial side effects),
// copies ./stderr.txt to stderr. ----
function diffSetup(spec = {}) {
    const dir = mkdtempSync(join(tmpdir(), 'bbq-diff-'));
    const log = join(dir, 'argv.log');
    const sh = `#!/bin/sh
echo "$(basename "$PWD") $*" >> ${JSON.stringify(log)}
case "$1" in
  --version) [ -z "\${NODE_OPTIONS+x}" ] || exit 7; echo "\${FAKE_VER:-v26.8.2}"; exit 0 ;;
  --v8-options) cat ${JSON.stringify(join(FIX, 'v8-options-excerpt.txt'))}; exit 0 ;;
esac
[ -z "\${NODE_OPTIONS+x}" ] || exit 7
fn=; drv=
for a in "$@"; do case "$a" in --print-bytecode-filter=*) fn="\${a#--print-bytecode-filter=}" ;; -*) ;; *) drv="$a" ;; esac; done
[ -f "$drv" ] || { echo "Error: Cannot find module $drv" >&2; exit 1; }
f=$(printf '%s' "$fn" | tr ' ' '-')
k=$(( $(cat "./.$f.k" 2>/dev/null || echo 0) + 1 )); echo "$k" > "./.$f.k"
[ -f ./hook.sh ] && . ./hook.sh
[ -f ./stderr.txt ] && cat ./stderr.txt >&2
if [ -f "./$f.$k.txt" ]; then cat "./$f.$k.txt"; elif [ -f "./$f.txt" ]; then cat "./$f.txt"; fi
exit 0
`;
    const node = join(dir, 'node');
    writeFileSync(node, sh); chmodSync(node, 0o755);
    for (const side of ['b', 'a']) {
        mkdirSync(join(dir, side));
        writeFileSync(join(dir, side, 'driver.mjs'), `// ${side} driver (the fake node never runs it)\n`);
        for (const [fn, lens] of Object.entries(spec[side] || {})) writeFileSync(join(dir, side, `${fn.replace(/ /g, '-')}.txt`), capture(fn, lens));
    }
    return {
        dir, node, B: join(dir, 'b', 'driver.mjs'), A: join(dir, 'a', 'driver.mjs'),
        spawns: () => (existsSync(log) ? readFileSync(log, 'utf8').split('\n').filter(Boolean) : []),
        done: () => rmSync(dir, { recursive: true, force: true }),
    };
}
function capture(fn, lens) {
    return lens.map((n) => `[generated bytecode for function: ${fn} (0x1 <SharedFunctionInfo ${fn}>)]\nBytecode length: ${n}\nParameter count 1\n`).join('');
}
function diffRun(spec, fns, script = SCRIPT, extra = [], ropts = {}, prep = () => {}) {
    const s = diffSetup(spec);
    try {
        prep(s);
        const r = run(script, ['--diff', '--node', s.node, '--fn', fns, ...extra, s.B, s.A], ropts);
        return { r, spawns: s.spawns() };
    } finally { s.done(); }
}
// a row that must hold on the final build and exit 2 "unknown option --diff" on the base
function diffRow(name, body) {
    test(`bytecode-budget diff QA: ${name}`, { skip }, () => body(SCRIPT, true));
    // teeth: the SAME row body run against the base must fail (the base exits 2 "unknown option --diff")
    test(`bytecode-budget diff QA teeth: [${name}] is red on the a26e9f15 base`, { skip: baseSkip }, () => {
        assert.throws(() => body(BASE, false), assert.AssertionError);
    });
}


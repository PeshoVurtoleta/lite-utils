        const dir = mkdtempSync(join(tmpdir(), `bbq-${mname}-`));
        const tmp = mkdtempSync(join(tmpdir(), 'bbq-rtmp-'));
        const cwd = mkdtempSync(join(tmpdir(), 'bbq-rcwd-'));

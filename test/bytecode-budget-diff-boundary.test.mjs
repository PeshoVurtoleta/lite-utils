// exact name in diff mode: read never matches read.set / readAll / Store.read (red on M-prefix-match)
// =====================================================================================================
const PREFIX = {
    b: { read: [6] }, a: { read: [6] },
};
function prefixPrep(afterRead) {
    return (s) => {
        const hdr = (fn, n) => `[generated bytecode for function: ${fn} (0x1 <SharedFunctionInfo ${fn}>)]\nBytecode length: ${n}\n`;
        writeFileSync(join(s.dir, 'b', 'read.txt'), hdr('read', 6) + hdr('read.set', 40) + hdr('readAll', 50) + hdr('Store.read', 60));
        writeFileSync(join(s.dir, 'a', 'read.txt'), hdr('read', afterRead) + hdr('read.set', 41) + hdr('readAll', 51));
    };
}
diffRow('exact fn in diff mode: read vs read.set / readAll / Store.read -> only read counts (SAME, then DIFF on read)', (script) => {
    const s = diffRun(PREFIX, 'read', script, [], {}, prefixPrep(6));
    assert.equal(s.r.status, 0, s.r.stdout + s.r.stderr);
    assert.match(s.r.stdout, /^ {2}read: before 1 match\(es\): 6$/m); assert.match(s.r.stdout, /^ {2}read: after {2}1 match\(es\): 6$/m);
    const d = diffRun(PREFIX, 'read', script, [], {}, prefixPrep(7));
    assert.equal(d.r.status, 1, d.r.stdout + d.r.stderr);
    assert.match(d.r.stdout, /^ {2}read: DIFF -- length multiset differs \(before 6 \| after 7\)$/m);
});
test('bytecode-budget diff QA MUTANT M-prefix-match (a header name that starts with fn counts): the exact-name row goes red', { skip }, () => {
    const dir = mkdtempSync(join(tmpdir(), 'bbq-pfx-'));
    try {
        const p = variant(dir, 'prefix-match', 'want = (s == fn); n += want; next', 'want = (index(s, fn) == 1); n += want; next');
        const s = diffRun(PREFIX, 'read', p, [], {}, prefixPrep(6));
        assert.equal(s.r.status, 1, s.r.stdout + s.r.stderr); assert.match(s.r.stdout, /^ {2}read: before 3 match\(es\): 6,40,50$/m);
    } finally { rmSync(dir, { recursive: true, force: true }); }
});

